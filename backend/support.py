"""サーバー代の進み具合の棒（2026-09-26、利用者の希望）。

「サーバー代のおねがい」の欄と、共有したあとの欄に「○ 月のサーバー代 約N円のうちM円を支援でまかなえた」を
棒で見せる。数字はここに手で書き、`main.py` がHTMLの `<meta name="trackmento-support">` に差し込む
（画面のJSはそれを読むだけ。取りに行く通信は増やさない）。**変えたらデプロイで反映**（R2のCSS / JSは出し直さなくてよい）。

- `COST_JPY` … その月のサーバー代の見込み。`scripts/board_data.py` の `money()` の `jpy`
  （Renderのインスタンス＋帯域の超過＋R2の保存の超過を、その日のレートで円にしたもの）
- `RECEIVED_JPY` / `SUPPORTERS` … Bandcampで買ってもらった額とPayPalで届いた額（受け取った額）と人数。利用者から聞いて足す
- 月が変わったら `MONTH` を進め、受け取った額と人数を0に戻す。**戻し忘れても画面には月が出る**ので、嘘にはならない
- 利用者が伝える額は手数料を引いた後の金額（PayPalの3.6%＋40円などは差し引き済み）。そのまま足す
- 金額と人数だけを出す。**買った人の名前や、どの曲かは出さない**
"""

MONTH = "2026-11"
COST_JPY = 1101                    # 2026-11-01のmoney()（Starter $7.00 × 157.25、為替は10/30のECB、帯域は直近7日で超過なし）
RECEIVED_JPY = 1072                 # 151円（10/19のBandcampの売上。10月分だが、締めたあとに分かったので11月の棒に入れた。利用者の判断、11/2）＋230円（Bandcamp、11/8）＋442円（PayPal.me、11/8）＋249円（PayPal.me、11/9）
SUPPORTERS = 4


def meta() -> str:
    """`<meta name="trackmento-support">` の中身。「月,サーバー代,支援の額,人数」をカンマで並べる。"""
    return f"{MONTH},{COST_JPY},{RECEIVED_JPY},{SUPPORTERS}"
